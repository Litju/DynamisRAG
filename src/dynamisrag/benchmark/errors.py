"""Typed error surface for the RES-138 benchmark boundary.

Deliberately separate from the embedding boundary's
:mod:`dynamisrag.embedding.errors` hierarchy, for the same reason that one is
separate from the OpenSearch one: a benchmark failure and a serving failure are
different events, and a caller that catches one type must not silently swallow
the other. A benchmark run never serves anything, and a TEI deployment never
ranks candidates.

    BenchmarkError
      BenchmarkContractError    a frozen contract was violated before any work
      BenchmarkSourceError      a frozen source could not be obtained or verified
      BenchmarkArtifactError    an artifact, shard, run manifest or bundle is unusable
      BenchmarkExecutionError   the GPU/model run could not be performed honestly
      BenchmarkPreflightError   the preflight approval gate was not satisfied

**The untrusted-content policy, inherited from RES-137 and stated once here.**
BEIR documents and queries are third-party scientific literature. A document
text, a query text, a vector component and a model response body are therefore
never admitted into an exception message, a structured context field, a log line
or a summary. Every value these errors carry is written by this codebase or
generated by a tool: the operation, the workload name, the model id, the item
id, a count, a position, an expected value and an observed value.

**Two of those observed values are constrained, because they are the ones that
name the failure without quoting content.** ``expected``/``observed`` carry
digests, counts, dimensions, versions and revisions. An id is a corpus or query
identifier — a short label, not content — and is carried because an operator
debugging a rejected item needs to know *which* item without being told what it
says.

:class:`BenchmarkError` carries ``detail`` for a human reading a traceback and
:meth:`BenchmarkError.safe_summary` for everything a log line, a notebook cell
or an operator report should print instead. The summary is assembled only from
the structured fields, never from ``detail``, which is what makes it safe to
hand to a terminal without another review pass.
"""

from __future__ import annotations

from typing import ClassVar, Final

__all__ = [
    "MAX_SAFE_DETAIL_LENGTH",
    "BenchmarkArtifactError",
    "BenchmarkContractError",
    "BenchmarkError",
    "BenchmarkExecutionError",
    "BenchmarkPreflightError",
    "BenchmarkSourceError",
]

MAX_SAFE_DETAIL_LENGTH: Final[int] = 240
"""Longest single fragment an exception message may carry.

A length bound on an *application-authored* line, so a long model id or a
machine-generated class name cannot push the actionable sentence off the end of
a log line. It is a formatting rule, not a security control: nothing untrusted
is ever shortened into safety by it, because nothing untrusted is ever admitted.
"""


class BenchmarkError(Exception):
    """Base class for every failure at the benchmark boundary.

    Two views of the same failure, exactly as the embedding boundary has:

    ``detail``
        Long-form prose for a traceback, written by this codebase.

    :meth:`safe_summary`
        One line assembled from the class and the structured fields only.
        ``detail`` is deliberately excluded, which is what makes the result safe
        to print in a notebook or paste into a bug report.
    """

    _CATEGORY: ClassVar[str] = "BenchmarkError"
    """Application-authored label for this failure class, overridable per class
    and per instance where one class covers several distinct conditions."""

    def __init__(
        self,
        detail: str,
        *,
        operation: str,
        category: str | None = None,
        workload: str | None = None,
        model_id: str | None = None,
        item_id: str | None = None,
        expected: str | None = None,
        observed: str | None = None,
        count: int | None = None,
    ) -> None:
        """Record the prose ``detail`` plus the structured, content-safe context.

        Every optional field is a workload name, a model id, an item id, a digest,
        a count or a version string. None of them can carry a document text, a
        query text or a vector component, which is exactly why the summary is
        built from these and not from ``detail``.
        """
        super().__init__(detail)
        self.detail: Final[str] = detail
        self.operation: Final[str] = operation
        self.category: Final[str] = category if category is not None else type(self)._CATEGORY
        self.workload: Final[str | None] = workload
        self.model_id: Final[str | None] = model_id
        self.item_id: Final[str | None] = item_id
        self.expected: Final[str | None] = expected
        self.observed: Final[str | None] = observed
        self.count: Final[int | None] = count

    def __str__(self) -> str:
        return self.detail

    def safe_summary(self) -> str:
        """One content-safe line: category, operation, and the structured facts.

        Never derived from ``detail``. Carries the operation, the workload, the
        model, the item id and the expected/observed pair, which together are
        enough to act on without disclosing what the item says.
        """
        parts: list[str] = [self.category, f"operation={self.operation}"]
        for name, value in (
            ("workload", self.workload),
            ("model_id", self.model_id),
            ("item_id", self.item_id),
            ("expected", self.expected),
            ("observed", self.observed),
            ("count", self.count),
        ):
            if value is not None:
                parts.append(f"{name}={value}")
        return " ".join(parts)


class BenchmarkContractError(BenchmarkError):
    """A frozen benchmark contract was violated, and nothing was computed.

    Raised before any network request, any model load and any file write: a
    duplicate corpus id, a qrel that names a query or document the workload does
    not hold, a relevance value that is not an integer judgment, a candidate
    dimension outside the frozen set, a code identity that is not an exact
    40-character commit, a shard size that is not the frozen shard size.
    """

    _CATEGORY: ClassVar[str] = "ContractInvalid"


class BenchmarkSourceError(BenchmarkError):
    """A frozen workload source could not be obtained or could not be trusted.

    Every condition in which a source is *not* provably the frozen bytes:
    a download that failed, a SHA-256 that is not the frozen digest, an archive
    whose layout is not the expected BEIR layout, a member that cannot be
    parsed. A cached file is trusted on its digest alone — never on its name,
    its size or its position in a folder.
    """

    _CATEGORY: ClassVar[str] = "SourceUnverified"


class BenchmarkArtifactError(BenchmarkError):
    """An artifact, shard, run manifest or result bundle is unusable.

    A digest that does not match the bytes, a shard whose sidecar disagrees with
    its matrix, a run manifest that differs from the run being resumed, a bundle
    with a missing or duplicated shard, an artifact whose revision is not the
    revision this representation is defined by.
    """

    _CATEGORY: ClassVar[str] = "ArtifactInvalid"


class BenchmarkExecutionError(BenchmarkError):
    """The GPU run could not be performed, or not honestly.

    No CUDA device, a model revision that does not resolve to the pinned commit,
    prompt metadata at the pinned revision that does not describe the frozen
    prompts, a loaded model whose truncation boundary is shorter than the frozen
    native one, an input that exceeds the frozen sequence limit, or a returned
    matrix whose dtype, shape or finiteness is not what the artifact contract
    requires.

    The distinction from :class:`BenchmarkContractError` is who owns the value:
    a contract error means *this repository's* frozen constant was violated, an
    execution error means *the environment or the upstream model* disagreed with
    it.
    """

    _CATEGORY: ClassVar[str] = "ExecutionInvalid"


class BenchmarkPreflightError(BenchmarkError):
    """The preflight approval gate was not satisfied, so no full run may start.

    Raised when a full run is requested without a preflight artifact whose
    SHA-256 matches the approved digest exactly, when the preflight artifact is
    for a different code commit or a different runtime fingerprint, or when a
    model/path pair failed the MRL calibration gate and the run asked for a
    derived vector instead of a native one.
    """

    _CATEGORY: ClassVar[str] = "PreflightUnapproved"
